void apply(const Theme& t) {
    for (int i = 0; i < kNumSlots; ++i) *slot(i) = t.c[i];
}

Theme current(const char* name) {
    Theme t{name, {}};
    for (int i = 0; i < kNumSlots; ++i) t.c[i] = *slot(i);
    return t;
}

